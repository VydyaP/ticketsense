from __future__ import annotations

import time
from collections.abc import Callable

from prometheus_client import CONTENT_TYPE_LATEST, Counter, Histogram, generate_latest
from starlette.middleware.base import BaseHTTPMiddleware
from starlette.requests import Request
from starlette.responses import Response

# HTTP Metrics
HTTP_REQUESTS_TOTAL = Counter(
    "ticketsense_http_requests_total",
    "Total HTTP request count",
    ["method", "endpoint", "status_code"],
)

HTTP_REQUEST_DURATION_SECONDS = Histogram(
    "ticketsense_http_request_duration_seconds",
    "HTTP request latency in seconds",
    ["method", "endpoint"],
    buckets=(0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0),
)

# Domain Metrics
TICKET_PREDICTIONS_TOTAL = Counter(
    "ticketsense_ticket_predictions_total",
    "Total ticket predictions generated by model",
    ["category", "priority"],
)

TICKET_CORRECTIONS_TOTAL = Counter(
    "ticketsense_ticket_corrections_total",
    "Total ticket categories corrected by human agents",
    ["original_category", "corrected_category"],
)


class PrometheusMetricsMiddleware(BaseHTTPMiddleware):
    """Middleware collecting Prometheus HTTP request counts and latency histograms."""

    async def dispatch(self, request: Request, call_next: Callable) -> Response:
        if request.url.path in ("/metrics", "/health"):
            return await call_next(request)

        start_time = time.perf_counter()
        response: Response
        try:
            response = await call_next(request)
            status_code = str(response.status_code)
        except Exception as exc:
            status_code = "500"
            raise exc
        finally:
            duration = time.perf_counter() - start_time
            endpoint = request.url.path
            # Normalize IDs in path for Prometheus label cardinality: e.g. /api/tickets/123 -> /api/tickets/{id}
            if endpoint.startswith("/api/tickets/") and endpoint != "/api/tickets/":
                endpoint = "/api/tickets/{id}"

            HTTP_REQUESTS_TOTAL.labels(
                method=request.method,
                endpoint=endpoint,
                status_code=status_code,
            ).inc()

            HTTP_REQUEST_DURATION_SECONDS.labels(
                method=request.method,
                endpoint=endpoint,
            ).observe(duration)

        return response


def get_prometheus_metrics() -> Response:
    """Return current prometheus metrics formatted according to specification."""
    return Response(content=generate_latest(), media_type=CONTENT_TYPE_LATEST)
